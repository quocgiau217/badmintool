// tx("câu tiếng Việt", [giá trị…]) -> câu theo ngôn ngữ đang chọn
function tx(s, args) {
  s = String(s);
  let out = s;
  if (LANG === 'en') {
    const lead = s.match(/^\s*/)[0], trail = s.slice(lead.length).match(/\s*$/)[0];
    const core = s.trim().replace(/\s+/g, ' ');
    if (core && Object.prototype.hasOwnProperty.call(EN, core)) out = lead + EN[core] + trail;
  }
  return args ? out.replace(/\{(\d+)\}/g, (m, i) => (args[i] != null ? args[i] : '')) : out;
}
