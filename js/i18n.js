const THEMES = ['auto', 'light', 'dark'];
let THEME = (() => { try { const v = localStorage.getItem('xs_theme'); return THEMES.includes(v) ? v : 'auto'; } catch (e) { return 'auto'; } })();
function applyTheme() {
  if (typeof document === 'undefined') return;
  const r = document.documentElement;
  if (THEME === 'auto') r.removeAttribute('data-theme'); else r.setAttribute('data-theme', THEME);
  const dark = THEME === 'dark' || (THEME === 'auto' && window.matchMedia && matchMedia('(prefers-color-scheme: dark)').matches);
  const m = document.querySelector('meta[name="theme-color"]'); if (m) m.setAttribute('content', dark ? '#0b0f0d' : '#0e7a57');
}
function setTheme(v) {
  if (!THEMES.includes(v)) return;
  THEME = v; try { localStorage.setItem('xs_theme', v); } catch (e) {}
  applyTheme();
  if (typeof prefsReopen === 'function') prefsReopen();
}
